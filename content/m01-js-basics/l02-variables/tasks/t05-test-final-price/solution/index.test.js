import { finalPrice } from './index.js';

describe('finalPrice: НДС', () => {
  it('добавляет НДС к цене', () => {
    expect(finalPrice(1000, 10, 0), 'Цена 1000, НДС 10 процентов, доставки нет').toBe(1100);
  });

  it('учитывает ставку НДС из параметра', () => {
    expect(finalPrice(1000, 20, 0), 'Ставка 20 процентов').toBe(1200);
    expect(finalPrice(1000, 0, 0), 'Ставка 0 процентов').toBe(1000);
  });
});

describe('finalPrice: доставка', () => {
  it('прибавляет доставку к цене с НДС', () => {
    expect(finalPrice(1000, 10, 350), 'Цена 1000, НДС 10, доставка 350').toBe(1450);
  });
});

describe('finalPrice: строки из формы', () => {
  it('принимает цену строкой', () => {
    expect(finalPrice('1000', 10, 350), 'Цена "1000" строкой').toBe(1450);
  });
});
