import { invoiceTotal } from './index.js';

describe('invoiceTotal: округление', () => {
  it('НДС считается от всей суммы, а не от одной штуки', () => {
    expect(invoiceTotal('10.10', '3', 5, 0), 'Три штуки по 10,10, НДС 5 процентов').toBe(3182);
  });

  it('цена переводится в копейки с округлением', () => {
    expect(invoiceTotal('0.10', '3', 0, 0), 'Три штуки по 10 копеек без НДС').toBe(30);
    expect(invoiceTotal('19.99', '7', 0, 0), 'Семь штук по 19,99 без НДС').toBe(13993);
  });

  it('результат всегда целое число', () => {
    const result = invoiceTotal('33.33', '3', 18, 12345);
    expect(Number.isInteger(result), 'Итог 33,33 x 3 с НДС 18 и доставкой: целое число копеек').toBe(true);
  });
});

describe('invoiceTotal: ставки и доставка', () => {
  it('ставка 0 даёт сумму без НДС', () => {
    expect(invoiceTotal('100', '2', 0, 0), 'Ставка 0 процентов').toBe(20000);
  });

  it('доставка прибавляется после НДС', () => {
    expect(invoiceTotal('100', '1', 20, 5000), 'НДС считается только от товара, доставка не облагается').toBe(17000);
  });

  it('одна штука', () => {
    expect(invoiceTotal('99.90', '1', 20, 0), 'Одна штука за 99,90 с НДС 20').toBe(11988);
  });
});
