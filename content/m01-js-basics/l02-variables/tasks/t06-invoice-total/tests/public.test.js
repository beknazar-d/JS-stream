import { invoiceTotal } from './index.js';

describe('invoiceTotal: примеры из тикета', () => {
  it('считает счёт с НДС 20 процентов', () => {
    expect(invoiceTotal('19.99', '3', 20, 0), 'Три штуки по 19,99 с НДС 20 процентов').toBe(7196);
  });

  it('прибавляет доставку', () => {
    expect(invoiceTotal('19.99', '3', 20, 35000), 'То же плюс доставка 350 рублей').toBe(42196);
  });

  it('принимает числа вместо строк', () => {
    expect(invoiceTotal(250, 2, 20, 0), 'Две штуки по 250 рублей числами').toBe(60000);
  });
});
