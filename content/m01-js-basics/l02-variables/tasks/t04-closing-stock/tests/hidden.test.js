import { closingStock } from './index.js';

describe('closingStock: дробные значения', () => {
  it('килограммы с дробной частью', () => {
    expect(closingStock('12.5', '2.5', '5', '0.5'), 'Мука: 12,5 кг + 2,5 кг - 5 кг - 0,5 кг').toBe(9.5);
  });
});

describe('closingStock: пустые и некорректные поля', () => {
  it('пустое поле считается нулём', () => {
    expect(closingStock('40', '', '5', ''), 'Пустые графы поставок и списаний').toBe(35);
  });

  it('пробелы вокруг числа не мешают', () => {
    expect(closingStock(' 10 ', '5', '3', '0'), 'Остаток " 10 " с пробелами').toBe(12);
  });

  it('текст вместо числа даёт NaN', () => {
    expect(closingStock('40', 'abc', '5', '0'), 'В поставках "abc"').toBeNaN();
  });
});

describe('closingStock: смешанные типы', () => {
  it('числа и строки вместе', () => {
    expect(closingStock(100, '20', 30, '10'), 'Числа и строки вперемешку').toBe(80);
  });
});
