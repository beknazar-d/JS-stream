import { formatPhone, shippingLabel } from './index.js';

describe('formatPhone: примеры из тикета', () => {
  it('форматирует российский телефон', () => {
    expect(formatPhone('+79991234567'), 'Телефон +79991234567').toBe('+7 999 123-45-67');
  });

  it('пустой телефон', () => {
    expect(formatPhone(''), 'Пустой телефон').toBe('не указан');
  });
});

describe('shippingLabel: пример из тикета', () => {
  it('собирает этикетку из четырёх строк', () => {
    const label = shippingLabel(42, '  иванов анна ', ' Москва', 'ул. Ленина, 5 ', '+79991234567');
    expect(label, 'Этикетка для заказа 42').toBe(
      'ЗАКАЗ №000042\nИВАНОВ АННА\nг. Москва, ул. Ленина, 5\nТел.: +7 999 123-45-67',
    );
  });
});
