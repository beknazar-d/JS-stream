import { formatPhone, shippingLabel } from './index.js';

describe('formatPhone: некорректные телефоны', () => {
  it('телефон в формате 8 не подходит', () => {
    expect(formatPhone('89991234567'), 'Телефон с 8').toBe('не указан');
  });

  it('слишком короткий телефон', () => {
    expect(formatPhone('+7999'), 'Короткий телефон').toBe('не указан');
  });

  it('слишком длинный телефон', () => {
    expect(formatPhone('+799912345678'), 'Длинный телефон').toBe('не указан');
  });

  it('другая страна', () => {
    expect(formatPhone('+13105550123'), 'Телефон +1').toBe('не указан');
  });
});

describe('formatPhone: другие номера', () => {
  it('группы цифр', () => {
    expect(formatPhone('+74951234567'), 'Московский номер').toBe('+7 495 123-45-67');
  });
});

describe('shippingLabel: номер заказа', () => {
  it('номер строкой', () => {
    const label = shippingLabel('42', 'Петров Иван', 'Казань', 'ул. Баумана, 1', '+79991234567');
    expect(label.startsWith('ЗАКАЗ №000042\n'), 'Номер "42" строкой').toBe(true);
  });

  it('длинный номер не обрезается', () => {
    const label = shippingLabel(1234567, 'Петров Иван', 'Казань', 'ул. Баумана, 1', '+79991234567');
    expect(label.startsWith('ЗАКАЗ №1234567\n'), 'Семизначный номер').toBe(true);
  });
});

describe('shippingLabel: имя, адрес и телефон', () => {
  it('имя поднимается в верхний регистр', () => {
    const label = shippingLabel(1, 'сидорова мария', 'Тверь', 'пр. Мира, 10', '+79991234567');
    expect(label, 'Имя строчными буквами').toBe(
      'ЗАКАЗ №000001\nСИДОРОВА МАРИЯ\nг. Тверь, пр. Мира, 10\nТел.: +7 999 123-45-67',
    );
  });

  it('пустой телефон подписывается «не указан»', () => {
    const label = shippingLabel(5, 'Орлов Пётр', 'Омск', 'ул. Ленина, 3', '');
    expect(label, 'Пустой телефон').toBe('ЗАКАЗ №000005\nОРЛОВ ПЁТР\nг. Омск, ул. Ленина, 3\nТел.: не указан');
  });

  it('этикетка состоит ровно из четырёх строк', () => {
    const label = shippingLabel(5, 'Орлов Пётр', 'Омск', 'ул. Ленина, 3', '+79991234567');
    expect(label.split('\n'), 'Строк в этикетке').toHaveLength(4);
  });
});
