import { normalizePhone } from './index.js';

describe('normalizePhone: другие начала номера', () => {
  it('номер начинается с 7 без плюса', () => {
    expect(normalizePhone('7-999-123-45-67'), 'Номер с 7 и дефисами').toBe('+79991234567');
  });

  it('номер без разделителей', () => {
    expect(normalizePhone('89991234567'), 'Сплошная строка с 8').toBe('+79991234567');
  });

  it('пробелы по краям и скобки без пробелов', () => {
    expect(normalizePhone(' +7(999)1234567 '), 'Пробелы по краям').toBe('+79991234567');
  });

  it('уже правильный номер', () => {
    expect(normalizePhone('+79991234567'), 'Номер уже в нужном виде').toBe('+79991234567');
  });
});

describe('normalizePhone: нельзя привести', () => {
  it('слишком короткий номер', () => {
    expect(normalizePhone('8 (999) 123-45-6'), 'Не хватает цифры').toBe('');
  });

  it('слишком длинный номер', () => {
    expect(normalizePhone('+7 (999) 123-45-678'), 'Лишняя цифра').toBe('');
  });

  it('номер другой страны', () => {
    expect(normalizePhone('+1 999 123 45 67'), 'Код +1').toBe('');
  });

  it('пустые строки', () => {
    expect(normalizePhone(''), 'Пустая строка').toBe('');
    expect(normalizePhone('   '), 'Строка из пробелов').toBe('');
  });

  it('только код страны', () => {
    expect(normalizePhone('+7'), 'Только +7').toBe('');
  });
});
