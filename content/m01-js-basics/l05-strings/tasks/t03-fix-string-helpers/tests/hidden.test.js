import { cleanSku, compactPhone, orderLabel } from './index.js';

describe('cleanSku: другие значения', () => {
  it('пробелы справа тоже убираются', () => {
    expect(cleanSku('rn-4521-blk '), 'Артикул с пробелом справа').toBe('RN-4521-BLK');
  });

  it('пробелы с обеих сторон', () => {
    expect(cleanSku('  sk-1  '), 'Артикул с пробелами с двух сторон').toBe('SK-1');
  });

  it('чистый артикул не меняется', () => {
    expect(cleanSku('AB-77'), 'Чистый артикул').toBe('AB-77');
  });
});

describe('compactPhone: другие значения', () => {
  it('телефон начинается с 8', () => {
    expect(compactPhone('8 999 123 45 67'), 'Телефон с пробелами').toBe('89991234567');
  });

  it('чистый телефон не меняется', () => {
    expect(compactPhone('+79991234567'), 'Уже чистый телефон').toBe('+79991234567');
  });

  it('много дефисов подряд', () => {
    expect(compactPhone('8-999-123-45-67'), 'Телефон только с дефисами').toBe('89991234567');
  });
});

describe('orderLabel: другие значения', () => {
  it('номер строкой с буквой', () => {
    expect(orderLabel('A-7'), 'Номер A-7').toBe('Заказ №A-7');
  });

  it('нулевой номер', () => {
    expect(orderLabel(0), 'Номер 0').toBe('Заказ №0');
  });
});
