import { buildInstallmentPlan } from './index.js';

describe('buildInstallmentPlan', () => {
  it('цена делится без остатка', () => {
    expect(
      buildInstallmentPlan(12000, 4),
      'График на 12 000 рублей и 4 месяца',
    ).toBe('Месяц 1: 3000 руб.\nМесяц 2: 3000 руб.\nМесяц 3: 3000 руб.\nМесяц 4: 3000 руб.\nИтого: 12000 руб.');
  });

  it('остаток уходит в последний платёж', () => {
    expect(
      buildInstallmentPlan(10000, 3),
      'График на 10 000 рублей и 3 месяца',
    ).toBe('Месяц 1: 3333 руб.\nМесяц 2: 3333 руб.\nМесяц 3: 3334 руб.\nИтого: 10000 руб.');
  });
});
