import { sellerPayout, canPayOut } from './index.js';

describe('sellerPayout: примеры из тикета', () => {
  it('выручка минус комиссия плюс премия', () => {
    expect(sellerPayout(100000, 10, 5000), 'Выручка 1000 рублей, комиссия 10 процентов, премия 50 рублей').toBe(95000);
  });

  it('нулевая комиссия остаётся нулём', () => {
    expect(sellerPayout(100000, 0, 0), 'Партнёр без комиссии').toBe(100000);
  });

  it('комиссия по умолчанию', () => {
    expect(sellerPayout(100000, null, null), 'Комиссия и премия не заданы').toBe(90000);
  });
});

describe('canPayOut: примеры из тикета', () => {
  it('выплата в рабочий день разрешена', () => {
    expect(canPayOut(100000, false, false), 'Ровно 1000 рублей, будний день, продавец активен').toBe(true);
  });

  it('выплата меньше порога запрещена', () => {
    expect(canPayOut(99999, false, false), 'На копейку меньше порога').toBe(false);
  });
});
