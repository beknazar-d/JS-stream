import { addItem } from './index.js';

describe('addItem', () => {
  it('добавляет позицию к сумме', () => {
    expect(addItem(0, 300, 2), 'Пустая корзина, 2 штуки по 300').toBe(600);
  });

  it('количество по умолчанию — одна штука', () => {
    expect(addItem(600, 150), 'Корзина на 600, добавили товар за 150').toBe(750);
  });
});
