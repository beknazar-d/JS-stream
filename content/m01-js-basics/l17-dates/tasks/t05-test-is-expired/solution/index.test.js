import { isExpired } from './index.js';

const at = (iso) => new Date(iso);

describe('isExpired: до окончания', () => {
  it('за несколько дней до конца', () => {
    expect(isExpired('2025-03-05', at('2025-03-01T12:00:00Z')), 'За четыре дня до конца').toBe(false);
  });

  it('в первую миллисекунду последнего дня', () => {
    expect(isExpired('2025-03-05', at('2025-03-05T00:00:00.000Z')), 'Начало последнего дня').toBe(false);
  });

  it('в последнюю миллисекунду последнего дня', () => {
    expect(isExpired('2025-03-05', at('2025-03-05T23:59:59.999Z')), 'Конец последнего дня').toBe(false);
  });
});

describe('isExpired: после окончания', () => {
  it('в первую миллисекунду следующего дня', () => {
    expect(isExpired('2025-03-05', at('2025-03-06T00:00:00.000Z')), 'Начало следующего дня').toBe(true);
  });

  it('через несколько дней и через год', () => {
    expect(isExpired('2025-03-05', at('2025-03-10T12:00:00Z')), 'Через пять дней').toBe(true);
    expect(isExpired('2025-03-05', at('2026-03-05T00:00:00Z')), 'Через год').toBe(true);
  });

  it('граница работает на стыке месяцев и годов', () => {
    expect(isExpired('2025-12-31', at('2025-12-31T23:59:59.999Z')), 'Последняя миллисекунда года').toBe(false);
    expect(isExpired('2025-12-31', at('2026-01-01T00:00:00.000Z')), 'Первая миллисекунда нового года').toBe(true);
  });
});

describe('isExpired: плохая дата окончания', () => {
  it('текст вместо даты', () => {
    expect(() => isExpired('abc', at('2025-03-01T00:00:00Z')), 'Текст «abc»').toThrow('Некорректная дата окончания');
  });

  it('пустая строка и дата в русском формате', () => {
    expect(() => isExpired('', at('2025-03-01T00:00:00Z')), 'Пустая строка').toThrow('Некорректная дата окончания');
    expect(() => isExpired('05.03.2025', at('2025-03-01T00:00:00Z')), 'Формат ДД.ММ.ГГГГ').toThrow('Некорректная дата окончания');
  });
});
