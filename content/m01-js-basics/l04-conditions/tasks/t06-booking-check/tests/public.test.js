import { validateBooking, bookingTotal } from './index.js';

describe('validateBooking: примеры из тикета', () => {
  it('корректная заявка', () => {
    expect(validateBooking('2', '3', 4, 5), 'Двое гостей, три ночи, заезд через 5 дней').toBe('ok');
  });

  it('нулевое число гостей', () => {
    expect(validateBooking('0', '3', 4, 5), 'Гостей 0').toBe('Укажите число гостей');
  });

  it('слишком долгий срок', () => {
    expect(validateBooking('2', '31', 4, 5), '31 ночь').toBe('Срок проживания от 1 до 30 ночей');
  });

  it('гостей больше вместимости', () => {
    expect(validateBooking('5', '3', 4, 5), 'Пять гостей при вместимости четыре').toBe('Максимум гостей: 4');
  });

  it('заезд в прошлом', () => {
    expect(validateBooking('2', '3', 4, -1), 'Заезд вчера').toBe('Дата заезда в прошлом');
  });
});

describe('bookingTotal: примеры из тикета', () => {
  it('без скидки', () => {
    expect(bookingTotal(3, 500000), 'Три ночи по 5000 рублей').toBe(1500000);
  });

  it('скидка 10 процентов от 7 ночей', () => {
    expect(bookingTotal(7, 100000), 'Семь ночей по 1000 рублей').toBe(630000);
  });
});
