describe('Отчёт склада: итоговая строка', () => {
  it('итог через двоеточие и пробел', () => {
    const lines = runSnippet('index.js');
    expect(lines[4], 'Строка 5: итог. После двоеточия нужен пробел').toBe('Всего движений: 19');
  });

  it('весь отчёт совпадает', () => {
    expect(runSnippet('index.js'), 'Весь вывод скрипта').toEqual([
      'Отчёт склада',
      'В обработке: 12',
      'Отгружено: 5',
      'Возвраты: 2',
      'Всего движений: 19',
    ]);
  });
});
