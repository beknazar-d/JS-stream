import { nodeMajor } from './index.js';

describe('nodeMajor: краевые случаи', () => {
  it('однозначная мажорная версия', () => {
    expect(nodeMajor('v8.17.0'), 'Вывод «v8.17.0»').toBe(8);
  });

  it('пробелы и перевод строки по краям', () => {
    expect(nodeMajor('  v18.19.0\n'), 'Вывод с пробелами и переводом строки').toBe(18);
    expect(nodeMajor('v22.22.0\n'), 'Вывод с переводом строки в конце').toBe(22);
  });

  it('версия из трёх цифр и версия без патча', () => {
    expect(nodeMajor('v120.0.1'), 'Три цифры в первой части').toBe(120);
    expect(nodeMajor('v24.1.0'), 'Вывод «v24.1.0»').toBe(24);
  });
});
