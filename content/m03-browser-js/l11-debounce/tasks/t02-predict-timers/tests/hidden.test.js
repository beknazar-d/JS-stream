import { output } from './answer.js';

// Ожидаемый вывод проверен реальным запуском кода из snippet.js в Node 22.
// runSnippet здесь не подходит: он собирает только вывод до первого таймера.
const expected = [
  'ввод: ч',
  'ввод: чай',
  'конец скрипта',
  'нулевая задержка',
  'поиск: чай',
  'ввод: чайник',
  'поиск: чайник',
];

describe('Предсказание вывода', () => {
  expected.forEach((line, index) => {
    it(`строка ${index + 1} совпадает с выводом`, () => {
      expect(output[index], `Строка ${index + 1} вывода`).toBe(line);
    });
  });
});
